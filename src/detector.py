# Dramatic & hook trigger dictionaries
HOOK_VERBS_KEYWORDS = {
    'marry', 'wedding', 'fiancé', 'fiance', 'altar', 'bride', 'groom',
    'betray', 'cheating', 'mistress', 'bastard', 'divorce', 'disown',
    'slap', 'hands off', 'touch her', 'guards', 'arrest', 'kill', 'die',
    'kneel', 'beg', 'worthless', 'plainness', 'humiliate', 'turn around',
    'enough', 'liar', 'stole', 'stolen', 'disgrace', 'shame', 'leave',
    'bastard', 'poison', 'duke', 'soldier', 'broken', 'refuse', 'never'
}

INTENSE_TONES = {
    'cold', 'callous', 'cruel', 'venomous', 'furious', 'hysterical',
    'thunderous', 'deadly', 'dangerous', 'uncompromising', 'desperate',
    'mocking', 'spiteful', 'arrogant', 'scornful', 'incredulous',
    'begging', 'screaming', 'shouting', 'imperious', 'raw', 'vicious'
}

CLIFFHANGER_KEYWORDS = {
    'cliffhanger', 'cut to black', 'drone swells', 'peak', 'ominous',
    'accept my hand', 'marry me', 'what did you say', 'tell me',
    'who are you', 'how dare you', 'or else', 'not anymore', 'you have no idea'
}

class PromoCandidate:
    def __init__(self, episode_number: int, start_time: float, end_time: float,
                 hook_block: ScriptBlock, cliffhanger_block: ScriptBlock,
                 blocks_in_range: List[ScriptBlock], hook_score: float,
                 cliffhanger_score: float, coherence_score: float):
        self.episode_number = episode_number
        self.start_time = start_time
        self.end_time = end_time
        self.duration = round(end_time - start_time, 2)
        self.hook_block = hook_block
        self.cliffhanger_block = cliffhanger_block
        self.blocks = blocks_in_range
        self.hook_score = hook_score
        self.cliffhanger_score = cliffhanger_score
        self.coherence_score = coherence_score
        
        # Weighted overall composite score (out of 100)
        self.total_score = round(
            (hook_score * 0.40 + cliffhanger_score * 0.35 + coherence_score * 0.25) * 10, 1
        )
        
        # Descriptions generated by rule or LLM
        self.hook_description = ""
        self.cliffhanger_description = ""
        self.why_it_works = ""
        self.funnel_type = ""
        self.rank = 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "rank": self.rank,
            "episode": self.episode_number,
            "start_time": format_time(self.start_time),
            "end_time": format_time(self.end_time),
            "start_seconds": self.start_time,
            "end_seconds": self.end_time,
            "duration_seconds": self.duration,
            "total_score": self.total_score,
            "hook_score": round(self.hook_score, 1),
            "cliffhanger_score": round(self.cliffhanger_score, 1),
            "coherence_score": round(self.coherence_score, 1),
            "hook": self.hook_description,
            "cliffhanger": self.cliffhanger_description,
            "why_it_works": self.why_it_works,
            "funnel_type": self.funnel_type,
            "dialogue_exchanges": len([b for b in self.blocks if b.block_type == 'DIALOGUE'])
        }

def score_hook(block: ScriptBlock, early_blocks: List[ScriptBlock]) -> float:
    """Evaluates hook potential in the opening 3 seconds (0-10)."""
    score = 4.0
    text = (block.content + " " + " ".join(b.content for b in early_blocks)).lower()
    
    # Keyword hits
    kw_hits = sum(1 for kw in HOOK_VERBS_KEYWORDS if kw in text)
    score += min(3.5, kw_hits * 1.2)
    
    # Tone intensity
    if block.tone:
        tone_lower = block.tone.lower()
        if any(t in tone_lower for t in INTENSE_TONES):
            score += 2.0

    # Physical confrontation or visual shock
    if block.block_type == 'ACTION' and any(k in text for k in ['slap', 'grab', 'seized', 'tears', 'gun', 'sword']):
        score += 2.0
    elif block.block_type == 'DIALOGUE':
        # Short punchy lines hook faster than long exposition
        word_count = len(block.content.split())
        if 2 <= word_count <= 12:
            score += 1.0

    return min(10.0, round(score, 1))

def score_cliffhanger(end_block: ScriptBlock, late_blocks: List[ScriptBlock]) -> float:
    """Evaluates cliffhanger strength in the closing moments (0-10)."""
    score = 4.0
    all_late_text = (end_block.content + " " + " ".join(b.content for b in late_blocks)).lower()
    
    # Sound FX or Cut to Black cues
    if any(k in all_late_text for k in CLIFFHANGER_KEYWORDS):
        score += 3.0
        
    # Punctuation indicating unresolved shock
    if end_block.block_type == 'DIALOGUE':
        content = end_block.content.strip()
        if content.endswith('?'):
            score += 2.0
        elif content.endswith('...') or content.endswith('—'):
            score += 2.5
        elif any(k in content.lower() for k in ['marry', 'kill', 'leave', 'never', 'hand', 'choose', 'father']):
            score += 1.5

    # High stakes action ending (e.g. on knee proposing, gun raised, tear rolling)
    if end_block.block_type == 'ACTION':
        if any(k in all_late_text for k in ['knee', 'propos', 'knuckle', 'fury', 'black', 'gasp']):
            score += 2.5

    return min(10.0, round(score, 1))

def score_coherence(blocks: List[ScriptBlock]) -> float:
    """Evaluates whether the 20-60s clip forms a compelling standalone narrative arc (0-10)."""
    dialogues = [b for b in blocks if b.block_type == 'DIALOGUE']
    speakers = set(b.speaker for b in dialogues if b.speaker)
    
    score = 5.0
    # Two or more distinct speakers having conflict is ideal for short drama
    if len(speakers) >= 2:
        score += 2.5
    elif len(speakers) == 1:
        score += 0.5
        
    # Ideal number of dialogue lines for a 30-50s clip is between 4 and 10
    if 4 <= len(dialogues) <= 12:
        score += 2.0
    elif len(dialogues) < 2:
        score -= 2.0  # Too quiet, lacks dialogue hook for social video
        
    return min(10.0, max(1.0, round(score, 1)))

def find_promos_for_episode(episode: Episode, 
                            min_duration: float = 20.0, 
                            max_duration: float = 60.0,
                            top_k: int = 2) -> List[PromoCandidate]:
    """Scans an episode to find the best 20-60s promo windows."""
    blocks = episode.blocks
    candidates: List[PromoCandidate] = []
    
    # Identify potential start points (dialogue or intense action)
    for i, start_b in enumerate(blocks):
        # We only start on dialogue or intense action
        if start_b.block_type not in ('DIALOGUE', 'ACTION'):
            continue
            
        t_start = start_b.start_time
        
        # Look ahead for valid end points
        for j in range(i + 1, len(blocks)):
            end_b = blocks[j]
            t_end = end_b.end_time
            dur = t_end - t_start
            
            if dur < min_duration:
                continue
            if dur > max_duration:
                break  # Sorted by time, so further blocks will exceed max_duration
                
            # Valid candidate window found
            window_blocks = blocks[i:j+1]
            early_blocks = [b for b in window_blocks if b.start_time <= t_start + 3.5]
            late_blocks = [b for b in window_blocks if b.end_time >= t_end - 4.0]
            
            h_score = score_hook(start_b, early_blocks)
            c_score = score_cliffhanger(end_b, late_blocks)
            coh_score = score_coherence(window_blocks)
            
            cand = PromoCandidate(
                episode_number=episode.ep_number,
                start_time=t_start,
                end_time=t_end,
                hook_block=start_b,
                cliffhanger_block=end_b,
                blocks_in_range=window_blocks,
                hook_score=h_score,
                cliffhanger_score=c_score,
                coherence_score=coh_score
            )
            
            # Enrich with synthesized descriptions
            _generate_descriptions(cand)
            candidates.append(cand)
            
    # Deduplicate overlapping candidates: keep the highest scoring non-heavily-overlapping ones
    candidates.sort(key=lambda c: c.total_score, reverse=True)
    
    selected: List[PromoCandidate] = []
    for c in candidates:
        # Check overlap with already selected
        overlap = False
        for s in selected:
            # If start or end overlap by more than 15s in the same episode
            overlap_duration = max(0.0, min(c.end_time, s.end_time) - max(c.start_time, s.start_time))
            if overlap_duration > 15.0:
                overlap = True
                break
        if not overlap:
            selected.append(c)
            if len(selected) >= top_k:
                break
                
    return selected

def _generate_descriptions(cand: PromoCandidate):
    """Generates standard hook, cliffhanger, and 'why it works' summaries."""
    start_b = cand.hook_block
    end_b = cand.cliffhanger_block
    
    # Hook description
    if start_b.block_type == 'DIALOGUE':
        cand.hook_description = f"{start_b.speaker}: \"{start_b.content}\""
        if start_b.tone:
            cand.hook_description += f" ({start_b.tone})"
    else:
        cand.hook_description = f"Action: {start_b.content[:100]}"
        
    # Cliffhanger description
    if end_b.block_type == 'DIALOGUE':
        cand.cliffhanger_description = f"Cuts on {end_b.speaker}: \"{end_b.content}\""
    else:
        cand.cliffhanger_description = f"Cuts on: {end_b.content[:100]}"
        
    # Why it works
    if cand.episode_number <= 3:
        cand.funnel_type = "Cold Acquisition (Top-of-Funnel)"
        cand.why_it_works = "High-stakes public humiliation and betrayal immediately hooks cold viewers; unresolved climax forces app download."
    elif cand.total_score >= 85:
        cand.funnel_type = "High-Tension Retargeting"
        cand.why_it_works = "Explosive confrontation with rapid dialogue and an unanswered ultimatum that drives high click-through."
    else:
        cand.funnel_type = "Character Arc & Escalation"
        cand.why_it_works = "Presents a complete dramatic confrontation that exposes character hypocrisy before cutting off at the turning point."

