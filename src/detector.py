def _normalize_keywords(keywords: Optional[List[str]]) -> List[str]:
    if not keywords:
        return []
    return [k.strip().lower() for k in keywords if k and k.strip()]


class PromoCandidate:
    def __init__(
        self,
        episode_number: int,
        start_time: float,
        end_time: float,
        hook_block: ScriptBlock,
        cliffhanger_block: ScriptBlock,
        blocks_in_range: List[ScriptBlock],
        hook_score: float,
        cliffhanger_score: float,
        coherence_score: float,
        detection_method: str = "Manual / Rule-Based",
        proposed_by: Optional[List[str]] = None,
        model_scores: Optional[Dict[str, Any]] = None,
        judge_verdict: Optional[Dict[str, Any]] = None,
    ):
        self.episode_number = episode_number
        self.start_time = start_time
        self.end_time = end_time
        self.duration = round(end_time - start_time, 2)
        self.hook_block = hook_block
        self.cliffhanger_block = cliffhanger_block
        self.blocks = blocks_in_range
        self.hook_score = hook_score
        self.cliffhanger_score = cliffhanger_score
        self.coherence_score = coherence_score
        self.detection_method = detection_method
        self.proposed_by = proposed_by or [detection_method]
        self.model_scores = model_scores or {}
        self.judge_verdict = judge_verdict

        # Weighted overall composite score (out of 100)
        self.total_score = round(
            (hook_score * 0.40 + cliffhanger_score * 0.35 + coherence_score * 0.25) * 10,
            1,
        )

        # Descriptions generated by rule or LLM
        self.hook_description = ""
        self.cliffhanger_description = ""
        self.why_it_works = ""
        self.funnel_type = ""
        self.rank = 0

    def recalculate_total_score(self):
        self.total_score = round(
            (self.hook_score * 0.40 + self.cliffhanger_score * 0.35 + self.coherence_score * 0.25) * 10,
            1,
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "rank": self.rank,
            "episode": self.episode_number,
            "start_time": format_time(self.start_time),
            "end_time": format_time(self.end_time),
            "start_seconds": self.start_time,
            "end_seconds": self.end_time,
            "duration_seconds": self.duration,
            "total_score": self.total_score,
            "hook_score": round(self.hook_score, 1),
            "cliffhanger_score": round(self.cliffhanger_score, 1),
            "coherence_score": round(self.coherence_score, 1),
            "hook": self.hook_description,
            "cliffhanger": self.cliffhanger_description,
            "why_it_works": self.why_it_works,
            "funnel_type": self.funnel_type,
            "dialogue_exchanges": len([b for b in self.blocks if b.block_type == "DIALOGUE"]),
            "detection_method": self.detection_method,
            "proposed_by": self.proposed_by,
            "model_scores": self.model_scores,
            "judge_verdict": self.judge_verdict,
        }


def score_hook(
    block: ScriptBlock,
    early_blocks: List[ScriptBlock],
    custom_keywords: Optional[List[str]] = None,
    custom_only: bool = False,
) -> float:
    """Evaluates hook potential in the opening 3.5 seconds (0-10) using universal signals."""
    score = 3.5
    text = (block.content + " " + " ".join(b.content for b in early_blocks)).lower()
    custom_kws = _normalize_keywords(custom_keywords)

    if custom_kws:
        custom_hits = sum(1 for kw in custom_kws if kw in text)
        score += min(4.5, custom_hits * 1.8)

    if not custom_only:
        kw_hits = sum(1 for kw in UNIVERSAL_HOOK_KEYWORDS if kw in text)
        score += min(3.0, kw_hits * 1.1)

        # Punctuation & conversational shock (questions, exclamations, abrupt interruptions)
        if "?" in block.content or "!" in block.content:
            score += 1.0
        if "..." in block.content or "—" in block.content or "--" in block.content:
            score += 0.5

        # Tone intensity
        if block.tone:
            tone_lower = block.tone.lower()
            if any(t in tone_lower for t in INTENSE_TONES):
                score += 1.8

        # Rapid visual + verbal hook density in first 3.5s
        if len(early_blocks) >= 2:
            score += 0.6

        # Physical confrontation or visual shock
        action_tokens = {"slap", "grab", "seized", "tears", "gun", "knife", "sword", "shatter", "crash", "slam", "blood", "drop"}
        if block.block_type == "ACTION" and any(k in text for k in action_tokens):
            score += 1.8
        elif block.block_type == "DIALOGUE":
            word_count = len(block.content.split())
            if 2 <= word_count <= 13:
                score += 1.0

    return min(10.0, round(score, 1))


def score_cliffhanger(
    end_block: ScriptBlock,
    late_blocks: List[ScriptBlock],
    window_blocks: Optional[List[ScriptBlock]] = None,
    custom_keywords: Optional[List[str]] = None,
    custom_only: bool = False,
    cliffhanger_style: str = "any",
) -> float:
    """Evaluates cliffhanger strength in the closing moments (0-10) using universal signals."""
    score = 3.5
    all_late_text = (end_block.content + " " + " ".join(b.content for b in late_blocks)).lower()
    custom_kws = _normalize_keywords(custom_keywords)

    if custom_kws:
        custom_hits = sum(1 for kw in custom_kws if kw in all_late_text)
        score += min(4.8, custom_hits * 2.0)

    if not custom_only:
        cue_hits = sum(1 for k in UNIVERSAL_CLIFFHANGER_CUES if k.lower() in all_late_text)
        if cue_hits > 0:
            score += min(3.0, 1.5 + cue_hits * 0.8)

        # Unresolved syntax at cut-off
        content = end_block.content.strip()
        if end_block.block_type == "DIALOGUE":
            if content.endswith("?"):
                score += 2.3
            elif content.endswith("...") or content.endswith("—") or content.endswith("--"):
                score += 2.6
            elif content.endswith("!"):
                score += 1.4
            elif any(k in content.lower() for k in ("never", "leave", "choose", "truth", "secret", "stop", "wait", "kill", "dead", "you")):
                score += 1.0

            # Intense closing delivery tone
            if end_block.tone and any(t in end_block.tone.lower() for t in INTENSE_TONES):
                score += 1.0

        # High-stakes closing action/SFX/music cues
        if end_block.block_type in ("ACTION", "CAMERA", "SOUND FX", "MUSIC"):
            end_cues = {"black", "gasp", "freeze", "swell", "drone", "slam", "gun", "scream", "tears", "fury", "shock", "stinger", "silence", "drop"}
            if any(k in all_late_text for k in end_cues):
                score += 2.4

        # Pacing contrast: short punchy closing beat after longer dialogue builds cut tension
        if window_blocks and len(window_blocks) >= 4:
            avg_words = sum(len(b.content.split()) for b in window_blocks[:-1]) / max(1, len(window_blocks) - 1)
            end_words = len(end_block.content.split())
            if 1 <= end_words <= 8 and avg_words > end_words + 2:
                score += 0.8

    # Optional user-selected cliffhanger ending preference boost/penalty
    if cliffhanger_style == "question_ellipsis":
        c_end = end_block.content.strip()
        if c_end.endswith(("?", "...", "—", "--")):
            score += 1.5
        else:
            score -= 1.5
    elif cliffhanger_style == "action_audio":
        if end_block.block_type in ("ACTION", "CAMERA", "SOUND FX", "MUSIC"):
            score += 1.5
        else:
            score -= 1.0
    elif cliffhanger_style == "custom_only" and custom_kws:
        if not any(kw in all_late_text for kw in custom_kws):
            score -= 2.5

    return min(10.0, max(1.0, round(score, 1)))


def score_coherence(blocks: List[ScriptBlock]) -> float:
    """Evaluates whether the 20-60s clip forms a compelling standalone narrative arc (0-10)."""
    dialogues = [b for b in blocks if b.block_type == "DIALOGUE"]
    speakers = set(b.speaker for b in dialogues if b.speaker)

    score = 5.0
    if len(speakers) >= 2:
        score += 2.5
    elif len(speakers) == 1:
        score += 0.5

    if 4 <= len(dialogues) <= 14:
        score += 2.0
    elif len(dialogues) < 2:
        score -= 2.0

    # Reward conversational alternation (back-and-forth exchange rather than one monologue)
    switches = 0
    for idx in range(1, len(dialogues)):
        if dialogues[idx].speaker != dialogues[idx - 1].speaker:
            switches += 1
    if switches >= 3:
        score += 0.5

    return min(10.0, max(1.0, round(score, 1)))


def find_promos_for_episode(
    episode: Episode,
    min_duration: float = 20.0,
    max_duration: float = 60.0,
    top_k: int = 2,
    custom_hook_keywords: Optional[List[str]] = None,
    custom_cliffhanger_keywords: Optional[List[str]] = None,
    custom_only: bool = False,
    cliffhanger_style: str = "any",
) -> List[PromoCandidate]:
    """Scans an episode to find the best promo windows using universal + optional manual cliffhanger rules."""
    blocks = episode.blocks
    candidates: List[PromoCandidate] = []

    if not blocks:
        return candidates

    # Handle short inputs whose total runtime is slightly below min_duration gracefully
    effective_min = min_duration
    if episode.total_duration > 0 and episode.total_duration < min_duration:
        effective_min = max(5.0, episode.total_duration * 0.65)

    for i, start_b in enumerate(blocks):
        if start_b.block_type not in ("DIALOGUE", "ACTION"):
            continue

        t_start = start_b.start_time

        for j in range(i + 1, len(blocks)):
            end_b = blocks[j]
            t_end = end_b.end_time
            dur = t_end - t_start

            if dur < effective_min:
                continue
            if dur > max_duration:
                break

            window_blocks = blocks[i : j + 1]
            early_blocks = [b for b in window_blocks if b.start_time <= t_start + 3.5]
            late_blocks = [b for b in window_blocks if b.end_time >= t_end - 4.0]

            h_score = score_hook(
                start_b,
                early_blocks,
                custom_keywords=custom_hook_keywords,
                custom_only=custom_only,
            )
            c_score = score_cliffhanger(
                end_b,
                late_blocks,
                window_blocks=window_blocks,
                custom_keywords=custom_cliffhanger_keywords,
                custom_only=custom_only,
                cliffhanger_style=cliffhanger_style,
            )
            coh_score = score_coherence(window_blocks)

            cand = PromoCandidate(
                episode_number=episode.ep_number,
                start_time=t_start,
                end_time=t_end,
                hook_block=start_b,
                cliffhanger_block=end_b,
                blocks_in_range=window_blocks,
                hook_score=h_score,
                cliffhanger_score=c_score,
                coherence_score=coh_score,
                detection_method="Manual / Rule-Based",
                proposed_by=["Manual / Rule-Based"],
            )
            _generate_descriptions(cand)
            candidates.append(cand)

    candidates.sort(key=lambda c: c.total_score, reverse=True)

    selected: List[PromoCandidate] = []
    for c in candidates:
        overlap = False
        for s in selected:
            overlap_duration = max(0.0, min(c.end_time, s.end_time) - max(c.start_time, s.start_time))
            if overlap_duration > min(15.0, effective_min * 0.6):
                overlap = True
                break
        if not overlap:
            selected.append(c)
            if len(selected) >= top_k:
                break

    return selected


def build_manual_promo_candidate(
    episode: Episode,
    start_time: float,
    end_time: float,
    hook_note: str = "",
    cliffhanger_note: str = "",
    why_note: str = "",
) -> Optional[PromoCandidate]:
    """Creates a user-pinned manual cut promo candidate between start_time and end_time."""
    if not episode.blocks or end_time <= start_time:
        return None

    in_range = [b for b in episode.blocks if b.end_time > start_time and b.start_time < end_time]
    if not in_range:
        # Snap to nearest blocks
        closest_start = min(episode.blocks, key=lambda b: abs(b.start_time - start_time))
        closest_end = min(episode.blocks, key=lambda b: abs(b.end_time - end_time))
        i_idx = episode.blocks.index(closest_start)
        j_idx = episode.blocks.index(closest_end)
        if j_idx < i_idx:
            i_idx, j_idx = j_idx, i_idx
        in_range = episode.blocks[i_idx : j_idx + 1]

    start_b = in_range[0]
    end_b = in_range[-1]
    actual_start = min(start_time, start_b.start_time) if abs(start_b.start_time - start_time) > 2 else start_b.start_time
    actual_end = max(end_time, end_b.end_time) if abs(end_b.end_time - end_time) > 2 else end_b.end_time

    early_blocks = [b for b in in_range if b.start_time <= actual_start + 3.5]
    late_blocks = [b for b in in_range if b.end_time >= actual_end - 4.0]

    cand = PromoCandidate(
        episode_number=episode.ep_number,
        start_time=round(actual_start, 2),
        end_time=round(actual_end, 2),
        hook_block=start_b,
        cliffhanger_block=end_b,
        blocks_in_range=in_range,
        hook_score=score_hook(start_b, early_blocks),
        cliffhanger_score=score_cliffhanger(end_b, late_blocks, window_blocks=in_range),
        coherence_score=score_coherence(in_range),
        detection_method="Manual Cut",
        proposed_by=["User Manual Cut"],
    )
    _generate_descriptions(cand)
    if hook_note.strip():
        cand.hook_description = hook_note.strip()
    if cliffhanger_note.strip():
        cand.cliffhanger_description = cliffhanger_note.strip()
    if why_note.strip():
        cand.why_it_works = why_note.strip()
    else:
        cand.why_it_works = "Manually pinned editor cut targeting a specific opening hook and cliffhanger break."
    return cand


def _truncate_clean(text: str, limit: int = 115) -> str:
    cleaned = " ".join((text or "").split())
    if len(cleaned) <= limit:
        return cleaned
    cut = cleaned[:limit].rsplit(" ", 1)[0].rstrip(" ,;:-")
    return (cut or cleaned[:limit]) + "..."


def _generate_descriptions(cand: PromoCandidate):
    """Generates generic hook, cliffhanger, and 'why it works' summaries."""
    start_b = cand.hook_block
    end_b = cand.cliffhanger_block

    if start_b.block_type == "DIALOGUE":
        cand.hook_description = f"{start_b.speaker}: \"{start_b.content}\""
        if start_b.tone:
            cand.hook_description += f" ({start_b.tone})"
    else:
        cand.hook_description = f"Action: {_truncate_clean(start_b.content, 115)}"

    if end_b.block_type == "DIALOGUE":
        cand.cliffhanger_description = f"Cuts on {end_b.speaker}: \"{end_b.content}\""
    else:
        cand.cliffhanger_description = f"Cuts on: {_truncate_clean(end_b.content, 115)}"

    if cand.hook_score >= 8.0 and cand.cliffhanger_score >= 8.0:
        cand.why_it_works = "Strong immediate 0-3s hook paired with a high-tension unresolved cut-off that drives curiosity clicks."
    elif cand.total_score >= 80:
        cand.why_it_works = "Explosive confrontation with crisp turn-taking and an unanswered twist at the cut point."
    else:
        cand.why_it_works = "Self-contained dramatic exchange that establishes clear stakes before cutting off mid-escalation."


def _is_duke_show(episodes_map: Dict[int, Episode], show_title: str = "") -> bool:
    if "broken soldier" in (show_title or "").lower():
        return True
    speakers = set()
    for ep in list(episodes_map.values())[:5]:
        for b in ep.blocks:
            if b.speaker:
                speakers.add(b.speaker.upper())
    return "JULIANA" in speakers or "LADY JULIANA" in speakers or "CLARISSA" in speakers


def generate_dynamic_multi_segment_promos(
    episodes_map: Dict[int, Episode],
    promos: Optional[List[PromoCandidate]] = None,
) -> List[Dict[str, Any]]:
    """
    Dynamically synthesizes multi-segment stitched trailers (20s-60s total)
    by pairing top hook openers with top cliffhanger closers across any input.
    """
    if not episodes_map:
        return []

    candidate_pool = promos or []
    if not candidate_pool:
        for ep in list(episodes_map.values())[:10]:
            candidate_pool.extend(find_promos_for_episode(ep, min_duration=12.0, max_duration=35.0, top_k=2))

    if len(candidate_pool) < 2:
        return []

    by_hook = sorted(candidate_pool, key=lambda c: c.hook_score, reverse=True)
    by_cliff = sorted(candidate_pool, key=lambda c: c.cliffhanger_score, reverse=True)

    stitched: List[Dict[str, Any]] = []
    used_pairs = set()

    for h_cand in by_hook[:4]:
        for c_cand in by_cliff[:4]:
            if (h_cand.episode_number == c_cand.episode_number and abs(h_cand.start_time - c_cand.start_time) < 5.0):
                continue
            pair_key = (h_cand.episode_number, round(h_cand.start_time, 1), c_cand.episode_number, round(c_cand.start_time, 1))
            if pair_key in used_pairs:
                continue

            # Trim each segment cleanly along block boundaries to fit 20s-55s
            seg1_blocks = h_cand.blocks[: max(2, min(4, len(h_cand.blocks)))]
            seg2_blocks = c_cand.blocks[-max(2, min(5, len(c_cand.blocks))) :]
            s1_start, s1_end = seg1_blocks[0].start_time, seg1_blocks[-1].end_time
            s2_start, s2_end = seg2_blocks[0].start_time, seg2_blocks[-1].end_time
            d1 = round(max(1.0, s1_end - s1_start), 2)
            d2 = round(max(1.0, s2_end - s2_start), 2)
            total_dur = round(d1 + d2, 2)

            if 20.0 <= total_dur <= 60.0:
                used_pairs.add(pair_key)
                fmt = "Multi-Segment (Cross-Episode)" if h_cand.episode_number != c_cand.episode_number else "Multi-Segment (Intra-Episode)"
                avg_score = round((h_cand.hook_score * 5 + c_cand.cliffhanger_score * 5), 1)
                stitched.append({
                    "title": f"Dynamic Hook-to-Cliffhanger Stitch (Ep {h_cand.episode_number} + Ep {c_cand.episode_number})",
                    "format": fmt,
                    "marketing_tier": "Tier 1: Top-of-Funnel (Cold UA) - Dynamic Stitch",
                    "total_duration_seconds": total_dur,
                    "total_score": min(99.0, avg_score),
                    "segments": [
                        {
                            "segment_index": 1,
                            "episode": h_cand.episode_number,
                            "start_time": format_time(s1_start),
                            "end_time": format_time(s1_end),
                            "duration_seconds": d1,
                            "beat_description": h_cand.hook_description,
                        },
                        {
                            "segment_index": 2,
                            "episode": c_cand.episode_number,
                            "start_time": format_time(s2_start),
                            "end_time": format_time(s2_end),
                            "duration_seconds": d2,
                            "beat_description": c_cand.cliffhanger_description,
                        },
                    ],
                    "hook": h_cand.hook_description,
                    "cliffhanger": c_cand.cliffhanger_description,
                    "why_it_works": "Automatically pairs the sharpest 0-3s opening hook with an unresolved high-tension ending beat.",
                })
                if len(stitched) >= 2:
                    return stitched

    return stitched


